#!/usr/bin/env sh
# wbar-dual.sh - launch top bar (from config.ctl) + bottom taskbar-only bar
# usage: wbar-dual.sh [gen|run|kill]
#   gen  - (re)generate configs only, don't touch running waybar
#   run  - (default) generate + restart both bars
#   kill - stop both bars

scrDir="$(dirname "$(realpath "$0")")"
# shellcheck disable=SC1091
. "${scrDir}/globalcontrol.sh"
waybar_dir="${confDir}/waybar"
modules_dir="$waybar_dir/modules"
conf_file="$waybar_dir/config.jsonc"
bottom_file="$waybar_dir/config-bottom.jsonc"
style_file="$waybar_dir/style.css"

B_WIDTH=20
B_POS="right"

gen_bottom() {
    # 1. regenerate top bar + style from active 1| line (no restart by itself
    #    unless n/p arg given, so safe to call)
    "${scrDir}/wbarconfgen.sh" > /dev/null 2>&1

    # 2. compute taskbar sizing/theme same way wbarconfgen.sh does
    # right edge = vertical bar -> width + r_deg=270
    w_height="$B_WIDTH"
    i_task=$(( w_height * 6 / 10 ))
    if [ "$i_task" -lt 12 ]; then
        i_task="12"
    fi
    i_theme="$(
        { grep -q "^[[:space:]]*\$ICON[-_]THEME\s*=" "${hydeThemeDir}/hypr.theme" 2>/dev/null && grep "^[[:space:]]*\$ICON[-_]THEME\s*=" "${hydeThemeDir}/hypr.theme" | cut -d '=' -f2 | sed 's/^[[:space:]]*//;s/[[:space:]]*$//'; } ||
        grep 'gsettings set org.gnome.desktop.interface icon-theme' "${hydeThemeDir}/hypr.theme" 2>/dev/null | awk -F "'" '{print $((NF - 1))}'
    )"
    [ -z "$i_theme" ] && i_theme="Papirus"
    export r_deg=270
    export i_task
    export i_theme

    # 3. write right-edge config: taskbar only, in the center
    {
        echo '// --// right taskbar-only bar generated by wbar-dual.sh //-- //'
        echo ''
        echo '{'
        echo '    "layer": "top",'
        echo '    "output": [ "*" ],'
        echo '    "position": "right",'
        echo '    "mod": "dock",'
        echo "    \"width\": ${w_height},"
        echo '    "exclusive": true,'
        echo '    "passthrough": false,'
        echo '    "gtk-layer-shell": true,'
        echo '    "reload_style_on_change": true,'
        echo ''
        echo '    "modules-left": [],'
        echo '    "modules-center": ["custom/padd", "custom/l_end", "wlr/taskbar", "custom/r_end", "custom/padd"],'
        echo '    "modules-right": [],'
        echo ''
    } > "$bottom_file"

    # shellcheck disable=SC2016
    envsubst < "$modules_dir/taskbar.jsonc" >> "$bottom_file"
    echo '' >> "$bottom_file"
    cat "$modules_dir/footer.jsonc" >> "$bottom_file"
    echo "generated $bottom_file"
}

launch() {
    killall waybar 2>/dev/null
    sleep 0.5
    waybar --config "$conf_file" --style "$style_file" > /dev/null 2>&1 &
    waybar --config "$bottom_file" --style "$style_file" > /dev/null 2>&1 &
    echo "launched top ($conf_file) + right taskbar ($bottom_file)"
}

case "$1" in
    gen) gen_bottom ;;
    kill) killall waybar 2>/dev/null; echo "stopped both bars" ;;
    run|"") gen_bottom; launch ;;
    *) echo "usage: $(basename "$0") [gen|run|kill]"; exit 1 ;;
esac
